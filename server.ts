import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

  app.use(express.json({ limit: '50mb' }));
  app.use(express.urlencoded({ extended: true, limit: '50mb' }));

  // Initialize Gemini AI SDK
  const apiKey = process.env.GEMINI_API_KEY;
  const ai = new GoogleGenAI({
    apiKey: apiKey || '',
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });

  // Health check endpoint
  app.get('/api/health', (req, res) => {
    res.json({
      status: 'ok',
      hasApiKey: Boolean(apiKey && apiKey !== 'MY_GEMINI_API_KEY'),
    });
  });

  /**
   * Feature: Generate high-quality images using gemini-3-pro-image-preview
   * Supports imageSize: "1K", "2K", "4K"
   */
  app.post('/api/gemini/generate-hq', async (req, res) => {
    try {
      const { prompt, imageSize = '1K', aspectRatio = '1:1' } = req.body;

      if (!prompt || typeof prompt !== 'string') {
        return res.status(400).json({ error: 'Prompt is required' });
      }

      if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
        return res.status(400).json({
          error: 'Gemini API key is not configured. Please set your key in the AI Studio environment.',
        });
      }

      const validSizes = ['1K', '2K', '4K'];
      const chosenSize = validSizes.includes(imageSize) ? imageSize : '1K';

      // Use gemini-3-pro-image-preview as requested
      const response = await ai.models.generateContent({
        model: 'gemini-3-pro-image-preview',
        contents: {
          parts: [
            {
              text: prompt,
            },
          ],
        },
        config: {
          imageConfig: {
            aspectRatio: aspectRatio || '1:1',
            imageSize: chosenSize,
          },
        },
      });

      let imageUrl = '';
      let textResult = '';

      if (response.candidates?.[0]?.content?.parts) {
        for (const part of response.candidates[0].content.parts) {
          if (part.inlineData?.data) {
            const mime = part.inlineData.mimeType || 'image/png';
            imageUrl = `data:${mime};base64,${part.inlineData.data}`;
          } else if (part.text) {
            textResult += part.text;
          }
        }
      }

      if (!imageUrl) {
        return res.status(502).json({
          error: textResult || 'No image was generated by the model. Please refine your prompt.',
        });
      }

      return res.json({
        imageUrl,
        model: 'gemini-3-pro-image-preview',
        imageSize: chosenSize,
        textResult,
      });
    } catch (err: any) {
      console.error('Error generating image (gemini-3-pro-image-preview):', err);
      return res.status(500).json({
        error: err.message || 'Failed to generate image with gemini-3-pro-image-preview',
      });
    }
  });

  /**
   * Feature: Create & edit images using gemini-nano-banana-2.1
   * Supports text prompt + optional input image for editing/remixing
   */
  app.post('/api/gemini/create-or-edit', async (req, res) => {
    try {
      const { prompt, imageBase64, mimeType = 'image/png', aspectRatio = '1:1', imageSize = '1K' } = req.body;

      if (!prompt || typeof prompt !== 'string') {
        return res.status(400).json({ error: 'Prompt is required' });
      }

      if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
        return res.status(400).json({
          error: 'Gemini API key is not configured. Please set your key in the AI Studio environment.',
        });
      }

      const parts: any[] = [];

      // If an existing image was provided for editing:
      if (imageBase64) {
        // Strip data:image/...;base64, header if present
        const cleanBase64 = imageBase64.includes(',') ? imageBase64.split(',')[1] : imageBase64;
        parts.push({
          inlineData: {
            data: cleanBase64,
            mimeType: mimeType || 'image/png',
          },
        });
      }

      parts.push({
        text: prompt,
      });

      const validSizes = ['1K', '2K', '4K'];
      const chosenSize = validSizes.includes(imageSize) ? imageSize : '1K';

      // Model: gemini-nano-banana-2.1
      const response = await ai.models.generateContent({
        model: 'gemini-nano-banana-2.1',
        contents: {
          parts,
        },
        config: {
          imageConfig: {
            aspectRatio: aspectRatio || '1:1',
            imageSize: chosenSize,
          },
        },
      });

      let imageUrl = '';
      let textResult = '';

      if (response.candidates?.[0]?.content?.parts) {
        for (const part of response.candidates[0].content.parts) {
          if (part.inlineData?.data) {
            const mime = part.inlineData.mimeType || 'image/png';
            imageUrl = `data:${mime};base64,${part.inlineData.data}`;
          } else if (part.text) {
            textResult += part.text;
          }
        }
      }

      if (!imageUrl) {
        return res.status(502).json({
          error: textResult || 'No image was generated by gemini-nano-banana-2.1. Please refine your prompt.',
        });
      }

      return res.json({
        imageUrl,
        model: 'gemini-nano-banana-2.1',
        imageSize: chosenSize,
        textResult,
      });
    } catch (err: any) {
      console.error('Error with gemini-nano-banana-2.1:', err);
      return res.status(500).json({
        error: err.message || 'Failed to create or edit image with gemini-nano-banana-2.1',
      });
    }
  });

  // Mount Vite middleware in development or serve static in production
  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.join(__dirname, 'dist')));
    app.get('*', (req, res) => {
      res.sendFile(path.join(__dirname, 'dist', 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server running at http://localhost:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Server startup failed:', err);
  process.exit(1);
});
